begin;
set local plpgsql.check_asserts=on;
do $$
declare uid uuid:=gen_random_uuid(); sess uuid:=gen_random_uuid(); services uuid[]; qa_addon_uuid uuid; rejected boolean; result jsonb;
begin
  rejected:=false;
  begin perform public.spa_admin_save_addon('{}'); exception when insufficient_privilege then rejected:=true; end;
  assert rejected,'Guests cannot add add-ons';
  insert into auth.users(id,email) values(uid,'qa-addons@example.invalid');
  insert into auth.sessions(id,user_id) values(sess,uid);
  insert into public.spa_admins(user_id,role) values(uid,'admin');
  perform set_config('request.jwt.claims',jsonb_build_object('sub',uid,'role','authenticated','session_id',sess)::text,true);
  select array_agg(id) into services from (select id from public.spa_services where active order by name limit 2) s;
  result:=public.spa_admin_save_addon(jsonb_build_object('name','QA rollback add-on','price_cents',12550,'description','QA test','active',true,'service_ids',services));
  qa_addon_uuid:=(result->>'id')::uuid;
  assert (select price_cents=12550 and active from public.spa_addons where id=qa_addon_uuid),'Price and availability saved';
  assert (select count(*)=2 from public.spa_addon_services where spa_addon_services.addon_id=qa_addon_uuid),'Multiple services saved';
  assert exists(select 1 from jsonb_array_elements(public.spa_admin_data()->'addons') a where a->>'id'=qa_addon_uuid::text and jsonb_array_length(a->'service_ids')=2),'Dashboard returns service links';
  rejected:=false;begin perform public.spa_admin_save_addon(jsonb_build_object('name','qa ROLLBACK add-on','price_cents',100,'service_ids',services));exception when raise_exception then rejected:=true;end;
  assert rejected,'Duplicate names rejected without case sensitivity';
  perform public.spa_admin_save_addon(jsonb_build_object('id',qa_addon_uuid,'name','QA rollback add-on','price_cents',0,'active',false,'service_ids',array[services[1]]));
  assert (select price_cents=0 and not active from public.spa_addons where id=qa_addon_uuid),'Edit supports zero price and deactivation';
  assert (select count(*)=1 from public.spa_addon_services link where link.addon_id=qa_addon_uuid),'Editing replaces services';
  rejected:=false;begin perform public.spa_admin_save_addon(jsonb_build_object('id',qa_addon_uuid,'name','QA rollback add-on','price_cents',100,'service_ids','[]'::jsonb));exception when raise_exception then rejected:=true;end;
  assert rejected,'At least one service required';
  rejected:=false;begin perform public.spa_admin_save_addon(jsonb_build_object('id',qa_addon_uuid,'name','QA rollback add-on','price_cents',100,'service_ids',array[gen_random_uuid()]));exception when raise_exception then rejected:=true;end;
  assert rejected,'Unknown services rejected';
  assert (select count(*)=1 from public.spa_addon_services link where link.addon_id=qa_addon_uuid),'Failed edit preserves links';
  rejected:=false;begin perform public.spa_admin_save_addon(jsonb_build_object('name','QA invalid price','price_cents',-1,'service_ids',services));exception when raise_exception then rejected:=true;end;
  assert rejected,'Invalid prices rejected';
  assert not has_table_privilege('anon','public.spa_addons','select');
  assert not has_table_privilege('authenticated','public.spa_addon_services','insert');
  assert not has_function_privilege('anon','public.spa_admin_save_addon(jsonb)','execute');
  update public.spa_admins set active=false where user_id=uid;
  rejected:=false;begin perform public.spa_admin_save_addon('{}');exception when insufficient_privilege then rejected:=true;end;
  assert rejected,'Revoked admins cannot save add-ons';
end $$;
set local role authenticated;
do $$ begin assert (select count(*)=0 from public.spa_addons),'RLS hides add-ons from unauthorised users';assert (select count(*)=0 from public.spa_addon_services),'RLS hides service links';end $$;
reset role;
rollback;
select 'PASS: create/edit, multiple services, exact price, inactive and zero-price add-ons, duplicate and invalid input rejection, atomic service links, guest denial, revoked admin denial and RLS. Fixtures rolled back.' as result;
